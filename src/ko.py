KANJI = re.compile(r'[\u4e00-\u9fff\u3400-\u4dbf々〆]')
def _conv_raw(t):
    if t in SINGLE: return SINGLE[t]
    parts = re.findall(r'[\u4e00-\u9fff\u3400-\u4dbf々〆]+|[\u3040-\u309f]+|[\u30a0-\u30ffー]+', t)
    out = []; prev = None
    for n, p in enumerate(parts):
        kind = 'k' if KANJI.match(p) else 'h' if re.match(r'[\u3040-\u309f]', p) else 'a'
        if kind == 'k': piece = kanji2hangul(p)
        elif kind == 'h':
            if p == 'の' and 0 < n < len(parts)-1: piece = '의 '
            elif p == 'と' and 0 < n < len(parts)-1: piece = '와 '
            else: piece = kana2hangul(p)
        else: piece = kana2hangul(p)
        if out and prev and {prev, kind} == {'k', 'a'} and not out[-1].endswith(' '): out.append(' ')
        out.append(piece); prev = kind
    return ''.join(out)
