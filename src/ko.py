def _hira2kata(s): return ''.join(chr(ord(ch)+0x60) if 'ぁ' <= ch <= 'ゖ' else ch for ch in s)
def _jong(syl, j):  # 받침 붙이기 (j: 4=ㄴ, 19=ㅅ)
    o = ord(syl) - 0xAC00
    if not (0 <= o < 11172) or o % 28: return None
    return chr(0xAC00 + o + j)
RA = set('ラリルレロ')
VOW = set('アイウエオァィゥェォ')
U_FORM = {'ク':'크','グ':'그','ブ':'브','プ':'프','フ':'프','ト':'트','ド':'드'}
def kana2hangul(s):
    s = _hira2kata(s)
    units = []; i = 0
    while i < len(s):
        two = s[i:i+2]
        if len(two) == 2 and two in KANA: units.append(two); i += 2
        else: units.append(s[i]); i += 1
    out = []
    def nxt(k):
        for u in units[k+1:]:
            if u in ('ー',): continue
            return u
        return None
    for k, u in enumerate(units):
        if u == 'ン':
            if out and _jong(out[-1][-1], 4): out[-1] = out[-1][:-1] + _jong(out[-1][-1], 4)
            else: out.append('ㄴ')
            continue
        if u == 'ッ':
            if out and _jong(out[-1][-1], 19): out[-1] = out[-1][:-1] + _jong(out[-1][-1], 19)
            continue
        if u in ('ー', 'ヽ', 'ヾ'): continue
        n = nxt(k)
        end = n is None
        if u in U_FORM and (end or n[0] in RA or (u in 'トド' and n[0] in 'スズ')):
            # 영어 계열 외래어의 자음군·어말 자음 (블라, 크리, 링크, 스트)
            out.append(U_FORM[u]); continue
        if u in ('ム', 'ル') and (end or (n[0] not in VOW and n[0] not in 'ャュョン')):
            j = 16 if u == 'ム' else 8
            if out and _jong(out[-1][-1], j): out[-1] = out[-1][:-1] + _jong(out[-1][-1], j); continue
            out.append('므' if u == 'ム' else '르'); continue
        out.append(KANA.get(u, u))
    return ''.join(out)

# 한자 → 한국 한자음 (두음법칙 단순 적용)
CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
def _split(syl):
    o = ord(syl) - 0xAC00
    return o // 588, (o % 588) // 28, o % 28
def _join(c, v, j): return chr(0xAC00 + c*588 + v*28 + j)
IY = {2, 6, 7, 12, 17, 20}  # ㅑㅕㅖㅛㅠㅣ
def _dueum(syl, initial, prev):
    if not ('가' <= syl <= '힣'): return syl
    c, v, j = _split(syl)
    if initial:
        if c == 5: c = 11 if v in IY else 2      # ㄹ → ㅇ/ㄴ
        elif c == 2 and v in IY: c = 11          # ㄴ → ㅇ
    elif c == 5 and syl in ('렬', '률') and prev:
        pc, pv, pj = _split(prev) if '가' <= prev <= '힣' else (0, 0, 1)
        if pj in (0, 4): c = 11                   # 모음·ㄴ 뒤 렬/률 → 열/율
    return _join(c, v, j)
def kanji2hangul(run):
    out = []
    for k, ch in enumerate(run):
        r = HANJA.get(ch, ch)
        r = _dueum(r, k == 0, out[-1] if out else '')
        out.append(r)
    return ''.join(out)

